import React from "react";
import Link from "next/link";
import { notFound } from "next/navigation";
import { getAllRunIds, getNormalizedReport } from "@/lib/report/load";
import { StatusBadge } from "@/components/StatusBadge";
import { CodeBlock } from "@/components/CodeBlock";
import { SampleBanner } from "@/components/Banner";
import { Navbar } from "@/components/Navbar";
import { formatMoney } from "@/lib/report/format";
import { XCircle, HelpCircle, ShieldCheck } from "lucide-react";

export function generateStaticParams() {
  const ids = getAllRunIds();
  return ids.map((runId) => ({ runId }));
}

interface PageProps {
  params: Promise<{ runId: string }>;
}

export default async function RejectedFindingsPage({ params }: PageProps) {
  const { runId } = await params;
  const report = getNormalizedReport(runId);

  if (!report) {
    notFound();
  }

  const rejected = report.rejectedFindings;
  const unresolved = report.unresolvedFindings;

  return (
    <div className="min-h-screen bg-[#f1f5f9] dark:bg-[#0b0f17] text-slate-900 dark:text-slate-100 flex flex-col font-sans transition-colors">
      {/* Top Navigation */}
      <Navbar
        breadcrumbs={[
          { label: "runs", href: "/" },
          { label: report.library.name, href: `/runs/${report.runId}` },
          { label: "rejected & unresolved" },
        ]}
      />

      {/* Main Container */}
      <main className="flex-1 max-w-6xl mx-auto px-4 sm:px-6 py-8 w-full space-y-8">
        {report.isSample && <SampleBanner />}

        {/* Narrative Banner: What We Tried to Disprove and What Survived */}
        <div className="border border-slate-200/90 dark:border-slate-800/80 rounded-xl p-6 bg-gradient-to-r from-rose-50/25 to-amber-50/25 dark:bg-none dark:bg-[#111722] space-y-3 transition-colors shadow-xs">
          <h1 className="text-sm font-semibold font-mono text-slate-900 dark:text-slate-100 uppercase tracking-wider flex items-center gap-2">
            <ShieldCheck className="w-4 h-4 text-slate-400" />
            Detective Refutation Audit: Disproved &amp; Ambiguous Hypotheses
          </h1>
          <p className="text-xs text-slate-600 dark:text-slate-400 font-sans leading-relaxed max-w-3xl">
            In Nightshift, rejected and unresolved findings are a core transparency feature, not an error log.
            Every candidate anomaly generated by property testing is aggressively cross-examined against documentation,
            parameter domains, and boundary tests. Below are the anomalies our refutation checks successfully disproved or marked ambiguous.
          </p>
          <div className="pt-2 flex flex-wrap items-center gap-4 text-xs font-mono text-slate-600 dark:text-slate-400 border-t border-slate-100 dark:border-slate-800/60">
            <span>Rejected: <strong className="text-rose-700 dark:text-rose-400">{rejected.length}</strong></span>
            <span>•</span>
            <span>Unresolved: <strong className="text-amber-700 dark:text-amber-400">{unresolved.length}</strong></span>
            <span>•</span>
            <span>
              Exploration Spend:{" "}
              <strong className="text-slate-900 dark:text-slate-100">
                {formatMoney(report.cost.rejectedCandidatesCost)}
              </strong>
            </span>
          </div>
        </div>

        {/* Rejected Section */}
        <div className="space-y-4">
          <div className="flex items-center justify-between">
            <h2 className="text-xs font-mono uppercase tracking-wider text-slate-700 dark:text-slate-300 font-semibold flex items-center gap-2">
              <XCircle className="w-4 h-4 text-rose-500" />
              Rejected Candidates ({rejected.length})
            </h2>
            <span className="text-[11px] font-mono text-slate-500">
              Disproven by investigator refutation checks
            </span>
          </div>

          {rejected.length === 0 ? (
            <div className="border border-slate-200 dark:border-slate-800/80 rounded-xl p-5 bg-white dark:bg-[#111722] text-xs font-mono text-slate-500 shadow-xs">
              No candidates were rejected in this run.
            </div>
          ) : (
            <div className="space-y-4">
              {rejected.map((f) => {
                const killingCheck = f.checks.find((c) => c.effect.toLowerCase() === "refutes");

                return (
                  <div
                    key={f.id}
                    className="border border-slate-200 dark:border-slate-800/80 rounded-xl overflow-hidden bg-white dark:bg-[#111722] font-mono text-xs space-y-0 transition-colors shadow-xs"
                  >
                    <div className="border-b border-slate-200 dark:border-slate-800/80 p-4 bg-slate-50/70 dark:bg-slate-900/40 flex flex-wrap items-center justify-between gap-2">
                      <div className="flex items-center gap-2">
                        <span className="text-slate-500">[{f.id}]</span>
                        <span className="font-semibold text-slate-700 dark:text-slate-300 line-through">
                          {f.title}
                        </span>
                      </div>
                      <div className="flex items-center gap-3">
                        <StatusBadge status={f.status} size="sm" />
                        <span className="text-slate-500 text-[11px] font-medium">{f.cost.formatted}</span>
                      </div>
                    </div>

                    <div className="p-5 space-y-4 font-sans text-xs">
                      {/* Reason */}
                      <div className="border border-rose-300 dark:border-rose-500/25 bg-rose-50/60 dark:bg-rose-500/5 rounded-lg p-3.5 space-y-1">
                        <span className="font-mono text-[10px] uppercase text-rose-700 dark:text-rose-400 block font-semibold">
                          Rejection Reason &amp; Refutation Verdict
                        </span>
                        <p className="text-rose-950 dark:text-rose-200 leading-relaxed">
                          {f.rejectionReason || "Input fell outside documented contract domain."}
                        </p>
                      </div>

                      {/* Killing Check */}
                      {killingCheck && (
                        <div className="border border-slate-200 dark:border-slate-800 rounded-lg p-3.5 bg-slate-50/70 dark:bg-[#0b0f17]/60 font-mono text-xs space-y-1.5">
                          <span className="text-[10px] text-slate-500 uppercase block font-semibold">
                            Refuting Check ({killingCheck.tool})
                          </span>
                          <div className="text-slate-800 dark:text-slate-200">
                            <strong>Q:</strong> {killingCheck.question}
                          </div>
                          <div className="text-slate-600 dark:text-slate-400">
                            <strong>A:</strong> {killingCheck.result}
                          </div>
                        </div>
                      )}

                      {/* Repro snippet */}
                      <CodeBlock
                        code={f.repro}
                        language="python"
                        title="Proposed Repro Script (Disproven)"
                      />
                    </div>
                  </div>
                );
              })}
            </div>
          )}
        </div>

        {/* Unresolved Section */}
        <div className="space-y-4">
          <div className="flex items-center justify-between">
            <h2 className="text-xs font-mono uppercase tracking-wider text-slate-700 dark:text-slate-300 font-semibold flex items-center gap-2">
              <HelpCircle className="w-4 h-4 text-slate-400" />
              Unresolved Candidates ({unresolved.length})
            </h2>
            <span className="text-[11px] font-mono text-slate-500">
              Ambiguous claims or documentation gaps
            </span>
          </div>

          {unresolved.length === 0 ? (
            <div className="border border-slate-200 dark:border-slate-800/80 rounded-xl p-5 bg-white dark:bg-[#111722] text-xs font-mono text-slate-500 shadow-xs">
              No candidates left unresolved in this run.
            </div>
          ) : (
            <div className="space-y-4">
              {unresolved.map((f) => (
                <div
                  key={f.id}
                  className="border border-slate-200 dark:border-slate-800/80 rounded-xl overflow-hidden bg-white dark:bg-[#111722] font-mono text-xs space-y-0 transition-colors shadow-xs"
                >
                  <div className="border-b border-slate-200 dark:border-slate-800/80 p-4 bg-slate-50/70 dark:bg-slate-900/40 flex flex-wrap items-center justify-between gap-2">
                    <div className="flex items-center gap-2">
                      <span className="text-slate-500">[{f.id}]</span>
                      <span className="font-semibold text-slate-800 dark:text-slate-200">
                        {f.title}
                      </span>
                    </div>
                    <div className="flex items-center gap-3">
                      <StatusBadge status={f.status} size="sm" />
                      <span className="text-slate-500 text-[11px] font-medium">{f.cost.formatted}</span>
                    </div>
                  </div>

                  <div className="p-5 space-y-4 font-sans text-xs">
                    {/* Uncertainty note */}
                    <div className="border border-slate-200 dark:border-slate-800 rounded-lg p-3.5 bg-slate-50/70 dark:bg-[#0b0f17]/60 space-y-1">
                      <span className="font-mono text-[10px] uppercase text-slate-600 dark:text-slate-400 block font-semibold">
                        Ambiguity / Uncertainty Assessment
                      </span>
                      <p className="text-slate-700 dark:text-slate-300 leading-relaxed">
                        {f.uncertainty || "Documentation ambiguous on grouping or commutativity."}
                      </p>
                    </div>

                    <CodeBlock
                      code={f.repro}
                      language="python"
                      title="Repro Script (Ambiguous Invariant)"
                    />
                  </div>
                </div>
              ))}
            </div>
          )}
        </div>
      </main>
    </div>
  );
}
