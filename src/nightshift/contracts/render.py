"""Render a frozen contract + audited adapter + strategy into one runnable pytest file.

The file prints one `NIGHTSHIFT_STATS {...}` line (run pytest with `-s`) with
non-vacuity counters: generated inputs that entered the body, passed the precondition,
reached the assertion, and how often each required API was actually called.
Counts include Hypothesis's shrink/replay phases; they are not `max_examples`.
"""

from __future__ import annotations

import json
from dataclasses import dataclass

from nightshift.contracts.audit import AuditResult, audit_source
from nightshift.contracts.model import Contract
from nightshift.contracts.templates import ADAPTER_FUNCTIONS, BODIES, template_hash

STATS_MARKER = "NIGHTSHIFT_STATS "


class HarnessRejected(ValueError):
    def __init__(self, problems: tuple[str, ...]):
        super().__init__("harness rejected:\n  " + "\n  ".join(problems))
        self.problems = problems


@dataclass(frozen=True)
class Harness:
    adapter_source: str  # defines the family's adapter functions
    strategy_source: str  # defines `inputs()` returning a Hypothesis strategy; `st` is provided

    def audit(self, contract: Contract) -> AuditResult:
        a = audit_source(self.adapter_source, required=ADAPTER_FUNCTIONS[contract.family], kind="adapter")
        s = audit_source(self.strategy_source, required=("inputs",), kind="strategy")
        return AuditResult(a.ok and s.ok, a.problems + s.problems)


_PRELUDE = '''# Generated by Nightshift. Do not edit: the contract and assertion are frozen.
# contract {contract_id} v{version} {contract_hash}
# template {family} {template_hash}
import copy, functools, importlib, inspect, json, types

from hypothesis import HealthCheck, assume, given, settings, strategies as st

CONTRACT_ID = {contract_id!r}
CONTRACT_HASH = {contract_hash!r}
_EQUIVALENCE = {equivalence!r}
_APIS = {apis!r}
_CALL_EVENTS = []
_FAILURE_API = None
_STATS = {{
    "contract_id": CONTRACT_ID, "contract_hash": CONTRACT_HASH, "template_hash": {template_hash!r},
    "entered": 0, "precondition_ok": 0, "assertion_reached": 0,
    "api_calls": {{}}, "untracked_apis": [], "failures": 0, "last_failure": None,
    "required_apis": _APIS,
}}


def _equiv(a, b):
    if _EQUIVALENCE == "type_and_value" and type(a) is not type(b):
        return False
    return a == b


def _fail(kind, x, **detail):
    _STATS["failures"] += 1
    _STATS["last_failure"] = {{"kind": kind, "input": x, **detail}}


def _track(dotted):
    """Count calls to a public API so an adapter that never calls it is caught as vacuous."""
    parts = dotted.split(".")
    for i in range(len(parts) - 1, 0, -1):
        try:
            owner = importlib.import_module(".".join(parts[:i]))
            break
        except ImportError:
            continue
    else:
        raise ImportError(f"cannot import any module prefix of {{dotted}}")
    for name in parts[i:-1]:
        owner = getattr(owner, name)
    attr = parts[-1]
    static = inspect.getattr_static(owner, attr)
    original = static.__func__ if isinstance(static, (staticmethod, classmethod)) else getattr(owner, attr)

    @functools.wraps(original)
    def counted(*args, **kwargs):
        _STATS["api_calls"][dotted] += 1
        event = {{"api": dotted, "args": args, "kwargs": kwargs}}
        _CALL_EVENTS.append(event)
        try:
            event["result"] = original(*args, **kwargs)
            return event["result"]
        except Exception as exc:
            event["error"] = exc
            raise

    wrapped = type(static)(counted) if isinstance(static, (staticmethod, classmethod)) else counted
    try:
        setattr(owner, attr, wrapped)
        _STATS["api_calls"][dotted] = 0
    except (AttributeError, TypeError):
        _STATS["untracked_apis"].append(dotted)


for _api in {apis!r}:
    _track(_api)


def _load(name, source, **inject):
    module = types.ModuleType(name)
    module.__dict__.update(inject)
    exec(compile(source, f"<{{name}}>", "exec"), module.__dict__)
    return module


_adapter = _load("nightshift_adapter", {adapter_source!r})
_strategy = _load("nightshift_strategy", {strategy_source!r}, st=st)
_precondition = eval(compile("lambda x: " + {precondition!r}, "<precondition>", "eval"))
'''

_RUNTIME = '''
class _UnsupportedDomain(Exception):
    pass

class _AdapterError(Exception):
    pass

class _FidelityError(Exception):
    pass

def _input_repr(x):
    try:
        return repr(x)
    except Exception:
        return "<unsupported input representation>"

def _snapshot(x):
    # Explicit first-release policy: only acyclic, built-in value trees. Custom
    # deepcopy hooks, iterators, handles and stateful instances require an approved
    # reconstruction policy; silently aliasing them would move the oracle.
    def validate(value, active):
        scalar = (type(None), bool, int, float, complex, str, bytes, bytearray)
        if type(value) in scalar:
            return
        if type(value) not in (list, tuple, dict, set, frozenset):
            raise _UnsupportedDomain(f"unsupported snapshot type: {type(value).__name__}")
        if id(value) in active:
            raise _UnsupportedDomain("cyclic values need an explicit reconstruction policy")
        active.add(id(value))
        items = list(value.keys()) + list(value.values()) if type(value) is dict else value
        for item in items:
            validate(item, active)
        active.remove(id(value))
    validate(x, set())
    try:
        return copy.deepcopy(x)
    except Exception as exc:
        raise _UnsupportedDomain(f"cannot snapshot input/output: {exc}") from exc

def _invoke(fn, value, api):
    """Receipt for the supported direct-call adapter policy.

    Each stage must pass its input to the declared target and return that target's
    result unchanged. Projections/normalization need a separate reviewed policy.
    This is a bounded execution check, not a proof of arbitrary Python semantics.
    """
    global _FAILURE_API
    _FAILURE_API = None
    start = len(_CALL_EVENTS)
    try:
        out = fn(value)
    except Exception as exc:
        events = _CALL_EVENTS[start:]
        if any(e["api"] == api and e.get("error") is exc and
               any(v is value for v in (*e["args"], *e["kwargs"].values())) for e in events):
            _FAILURE_API = api
            raise
        raise _AdapterError(f"adapter/setup raised {type(exc).__name__}: {exc}") from exc
    events = [e for e in _CALL_EVENTS[start:] if e["api"] == api]
    if not events:
        raise _FidelityError(f"adapter never called {api}")
    if not any("result" in e and e["result"] is out and
               any(v is value for v in (*e["args"], *e["kwargs"].values())) for e in events):
        raise _FidelityError(f"adapter must pass the stage input to {api} and return its result unchanged")
    return out
'''

_SUFFIX = '''

@settings(max_examples={max_examples}, deadline=None, database=None, derandomize={derandomize},
          suppress_health_check=[HealthCheck.too_slow, HealthCheck.filter_too_much])
@given(_strategy.inputs())
def _property(x):
    _CALL_EVENTS.clear()
    _STATS["entered"] += 1
    assume(_precondition(x))
    _STATS["precondition_ok"] += 1
    _check(x)


def test_contract():
    try:
        _property()
    finally:
        _STATS["body_entries"] = _STATS["entered"]
        _STATS["assertions_reached"] = _STATS["assertion_reached"]
        print("\\n{marker}" + json.dumps(_STATS, default=repr), flush=True)
'''


def render_test(
    contract: Contract, harness: Harness, *, max_examples: int = 200, derandomize: bool = False
) -> str:
    if contract.status == "ambiguous":
        raise HarnessRejected(("contract is ambiguous; resolve it before testing",))
    if len(contract.apis) != 2:
        raise HarnessRejected(("relation requires exactly two declared target APIs",))
    audit = harness.audit(contract)
    if not audit.ok:
        raise HarnessRejected(audit.problems)
    prelude = _PRELUDE.format(
        contract_id=contract.contract_id,
        version=contract.version,
        contract_hash=contract.hash,
        family=contract.family,
        template_hash=template_hash(contract.family),
        equivalence=contract.equivalence,
        apis=list(contract.apis),
        adapter_source=harness.adapter_source,
        strategy_source=harness.strategy_source,
        precondition=contract.precondition,
    )
    suffix = _SUFFIX.format(max_examples=max_examples, derandomize=derandomize, marker=STATS_MARKER)
    return prelude + _RUNTIME + BODIES[contract.family] + suffix


def parse_stats(stdout: str) -> dict | None:
    for line in reversed(stdout.splitlines()):
        if line.startswith(STATS_MARKER):
            try:
                stats = json.loads(line[len(STATS_MARKER):])
                counts = ("entered", "precondition_ok", "assertion_reached")
                if not isinstance(stats, dict) or any(type(stats.get(k)) is not int or stats[k] < 0 for k in counts):
                    return None
                if not isinstance(stats.get("api_calls"), dict):
                    return None
                return stats
            except (ValueError, TypeError):
                return None
    return None


def contract_json(contract: Contract) -> str:
    return json.dumps(contract.to_dict(), indent=2)
